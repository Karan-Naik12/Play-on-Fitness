-- Play on Fitness JP Nagar — Supabase PostgreSQL Schema
-- Run this script once in your Supabase Dashboard -> SQL Editor.

CREATE TABLE IF NOT EXISTS public.business_settings (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  business_name TEXT NOT NULL DEFAULT 'Play on Fitness',
  category TEXT NOT NULL DEFAULT 'Gym / Fitness Centre',
  address TEXT NOT NULL DEFAULT '2nd Floor, 309, 100 Feet Ring Road, near Delmia Circle, JP Nagar',
  city TEXT NOT NULL DEFAULT 'Bengaluru',
  state TEXT NOT NULL DEFAULT 'Karnataka',
  postal_code TEXT NOT NULL DEFAULT '560078',
  phone TEXT NOT NULL DEFAULT '',
  whatsapp_number TEXT NOT NULL DEFAULT '',
  email TEXT NOT NULL DEFAULT '',
  mon_sat_open TEXT NOT NULL DEFAULT '05:30',
  mon_sat_close TEXT NOT NULL DEFAULT '22:00',
  sun_open TEXT NOT NULL DEFAULT '06:30',
  sun_close TEXT NOT NULL DEFAULT '13:00',
  holidays_json JSONB NOT NULL DEFAULT '[]'::jsonb,
  slot_interval_minutes INTEGER NOT NULL DEFAULT 60,
  auto_confirm_bookings BOOLEAN NOT NULL DEFAULT FALSE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.services (
  id INTEGER PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  category TEXT NOT NULL,
  description TEXT NOT NULL,
  duration_minutes INTEGER NOT NULL DEFAULT 60,
  price INTEGER,
  image_url TEXT NOT NULL,
  is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  is_proposed BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.trainers (
  id INTEGER PRIMARY KEY,
  name TEXT NOT NULL,
  specialization TEXT NOT NULL,
  experience TEXT NOT NULL,
  qualifications TEXT NOT NULL,
  bio TEXT NOT NULL,
  photo_url TEXT NOT NULL DEFAULT '',
  is_placeholder BOOLEAN NOT NULL DEFAULT TRUE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.trainer_availability (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trainer_id INTEGER NOT NULL REFERENCES public.trainers(id) ON DELETE CASCADE,
  day_of_week INTEGER NOT NULL CHECK (day_of_week BETWEEN 0 AND 6),
  start_time TEXT NOT NULL,
  end_time TEXT NOT NULL,
  is_available BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (trainer_id, day_of_week)
);

CREATE TABLE IF NOT EXISTS public.appointments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_ref TEXT NOT NULL UNIQUE,
  service_id INTEGER NOT NULL,
  service_name TEXT NOT NULL DEFAULT '',
  trainer_id INTEGER,
  trainer_name TEXT,
  customer_name TEXT NOT NULL,
  customer_phone TEXT NOT NULL,
  customer_email TEXT NOT NULL,
  appointment_date DATE NOT NULL,
  start_time TEXT NOT NULL,
  end_time TEXT NOT NULL,
  duration_minutes INTEGER NOT NULL,
  status TEXT NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending', 'Confirmed', 'Cancelled', 'Completed')),
  notes TEXT NOT NULL DEFAULT '',
  reschedule_requested_date DATE,
  reschedule_requested_time TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_unique_active_trainer_slot
  ON public.appointments (appointment_date, start_time, trainer_id)
  WHERE status <> 'Cancelled' AND trainer_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.membership_plans (
  id INTEGER PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  duration_label TEXT NOT NULL,
  price INTEGER,
  description TEXT NOT NULL,
  benefits JSONB NOT NULL DEFAULT '[]'::jsonb,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.gallery_images (
  id INTEGER PRIMARY KEY,
  title TEXT NOT NULL,
  category TEXT NOT NULL,
  image_url TEXT NOT NULL,
  caption TEXT NOT NULL DEFAULT '',
  is_verified_photo BOOLEAN NOT NULL DEFAULT FALSE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.enquiries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL CHECK (type IN ('contact', 'membership')),
  plan_name TEXT NOT NULL DEFAULT '',
  name TEXT NOT NULL,
  phone TEXT NOT NULL,
  email TEXT NOT NULL,
  message TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'New' CHECK (status IN ('New', 'Reviewed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Enable Row Level Security
ALTER TABLE public.business_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.services ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.trainers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.trainer_availability ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.appointments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.membership_plans ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.gallery_images ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.enquiries ENABLE ROW LEVEL SECURITY;

-- Policies allowing booking/enquiry reads, inserts, updates & deletes when using publishable key
-- (For stricter production lockdown, configure SUPABASE_SERVICE_ROLE_KEY on the Express backend and restrict anon policies.)
DROP POLICY IF EXISTS "Allow public select appointments" ON public.appointments;
CREATE POLICY "Allow public select appointments"
  ON public.appointments FOR SELECT
  TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS "Allow public insert appointments" ON public.appointments;
CREATE POLICY "Allow public insert appointments"
  ON public.appointments FOR INSERT
  TO anon, authenticated
  WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public update appointments by booking_ref" ON public.appointments;
CREATE POLICY "Allow public update appointments by booking_ref"
  ON public.appointments FOR UPDATE
  TO anon, authenticated
  USING (true)
  WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public delete appointments" ON public.appointments;
CREATE POLICY "Allow public delete appointments"
  ON public.appointments FOR DELETE
  TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS "Allow public select enquiries" ON public.enquiries;
CREATE POLICY "Allow public select enquiries"
  ON public.enquiries FOR SELECT
  TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS "Allow public insert enquiries" ON public.enquiries;
CREATE POLICY "Allow public insert enquiries"
  ON public.enquiries FOR INSERT
  TO anon, authenticated
  WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public read catalog" ON public.services;
CREATE POLICY "Allow public read catalog" ON public.services FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "Allow public read trainers" ON public.trainers;
CREATE POLICY "Allow public read trainers" ON public.trainers FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "Allow public read plans" ON public.membership_plans;
CREATE POLICY "Allow public read plans" ON public.membership_plans FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "Allow public read gallery" ON public.gallery_images;
CREATE POLICY "Allow public read gallery" ON public.gallery_images FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "Allow public read settings" ON public.business_settings;
CREATE POLICY "Allow public read settings" ON public.business_settings FOR SELECT TO anon, authenticated USING (true);
